"""Turn an eval run into the files people read: transcripts, README scorecard, JSON."""

from __future__ import annotations

import json
import re
from pathlib import Path

README_START = "<!-- eval-scorecard:start -->"
README_END = "<!-- eval-scorecard:end -->"
ICON = {True: "✅", False: "❌", None: "➖"}


def _money(x: float | None) -> str:
    return "–" if x is None else f"${x:.3f}"


def _secs(x: float | None) -> str:
    return "–" if x is None else f"{x:.1f}s"


def _short(obj, limit: int = 220) -> str:
    text = json.dumps(obj, ensure_ascii=False)
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _cell(text) -> str:
    """Make text safe for a Markdown table cell."""
    return " ".join(str(text).split()).replace("|", "\\|")


def render_transcript(scenario: dict) -> str:
    lines = []
    for turn in scenario["turns"]:
        lines.append(f"Customer: {turn['customer']}")
        for ev in turn["events"]:
            if ev["kind"] == "text":
                lines.append(f"Bea: {ev['text']}")
            elif ev["kind"] == "tool_call":
                lines.append(f"  → {ev['name']}({_short(ev['input'])})")
            elif ev["kind"] == "tool_result":
                lines.append(f"  ← {_short(ev['result'])}")
            elif ev["kind"] == "notice":
                lines.append(f"  [notice: {ev['text']}]")
        lines.append("")
    return "\n".join(lines).rstrip()


def _meta_line(run: dict) -> str:
    agent_desc = f"agent `{run['model']}`" + (f" (effort {run['effort']})" if run.get("effort") else "")
    parts = [agent_desc, f"simulated customer `{run['simulator_model']}`"]
    if run.get("judge_model"):
        parts.append(f"judge `{run['judge_model']}`")
    if run.get("git_commit"):
        parts.append(f"commit `{run['git_commit']}`")
    return f"{run['generated_at'][:10]} · " + " · ".join(parts)


def _headline(s: dict) -> str:
    text = (f"**{s['scenarios_passed']}/{s['scenarios']} scenarios passed**, "
            f"{s['checks_passed']}/{s['checks_total']} checks, "
            f"{s['safety_failures']} safety failures")
    if s.get("errored"):
        text += f", {s['errored']} scenario run(s) hit an API error"
    return text


def scorecard_table(run: dict, link_prefix: str = "") -> str:
    rows = ["| Scenario | Procedure | Result | Checks | Model cost | Median reply |",
            "|---|---|:-:|:-:|--:|--:|"]
    per = {p["id"]: p for p in run["summary"]["per_scenario"]}
    for i, sc in enumerate(run["scenarios"], 1):
        p = per[sc["id"]]
        ok = sum(1 for c in sc["checks"] if c["passed"])
        n = sum(1 for c in sc["checks"] if c["passed"] is not None)
        result = ICON[sc["passed"]]
        if run["summary"]["runs"] > 1:
            result += f" {p['pass_rate']:.0%}"
        anchor = f"{link_prefix}#{i}-{sc['id']}"
        rows.append(f"| [{sc['title']}]({anchor}) | {sc['aop']} | {result} | {ok}/{n} | "
                    f"{_money(sc['metrics']['agent_cost_usd'])} | "
                    f"{_secs(sc['metrics']['median_reply_seconds'])} |")
    return "\n".join(rows)


def render_markdown(run: dict) -> str:
    s = run["summary"]
    out = [
        "# Bookly agent: eval transcripts",
        "",
        "Generated by [`evals/run_evals.py`](evals/run_evals.py). Each scenario opens with a "
        "scripted message, then a smaller Claude model plays the customer from a persona. The "
        "checks run over what the agent actually did (tool calls, replies), mostly as plain "
        "code; a few rubric questions go to an LLM judge. How it works: [`evals/README.md`](evals/README.md).",
        "",
        f"> {_meta_line(run)}",
        ">",
        f"> {_headline(s)}. Average model cost {_money(s['avg_cost_per_conversation_usd'])} "
        f"per conversation, median reply {_secs(s['median_reply_seconds'])}."
        + (f" Pass rates are over {s['runs']} runs; transcripts are from the first." if s["runs"] > 1 else ""),
        "",
        scorecard_table(run),
        "",
        "Transcript notation: `→` is a tool call the agent made, `←` is what the tool returned. "
        "The customer never sees those lines.",
        "",
    ]
    for i, sc in enumerate(run["scenarios"], 1):
        m = sc["metrics"]
        out += [
            "---",
            "",
            f'<a id="{i}-{sc["id"]}"></a>',
            f"## {i}. {sc['title']} · {sc['aop']} {ICON[sc['passed']]}",
            "",
            f"**What it tests:** {sc['tests']}",
            "",
            *([f"> **This scenario didn't finish:** {_cell(sc['error'])}", ""] if sc.get("error") else []),
            "| | Check | Kind | Detail |",
            "|:-:|---|---|---|",
        ]
        for c in sc["checks"]:
            out.append(f"| {ICON[c['passed']]} | {_cell(c['name'])} | {c['kind']} | {_cell(c['detail'])} |")
        out += [
            "",
            "```text",
            render_transcript(sc),
            "```",
            "",
            f"{m['customer_turns']} customer turns · {m['api_calls']} model calls · "
            f"{m['tool_calls']} tool calls · model cost {_money(m['agent_cost_usd'])} · "
            f"median reply {_secs(m['median_reply_seconds'])} · ended: "
            f"{ {'customer_done': 'customer was done', 'turn_limit': 'turn limit', 'error': 'error'}[sc['ended']] }",
            "",
        ]
    return "\n".join(out)


def render_readme_block(run: dict) -> str:
    s = run["summary"]
    return "\n".join([
        README_START,
        f"**Latest run** ({_meta_line(run)}): {_headline(s)}. "
        f"Average model cost **{_money(s['avg_cost_per_conversation_usd'])} per conversation**, "
        f"median reply {_secs(s['median_reply_seconds'])}.",
        "",
        scorecard_table(run, link_prefix="test_transcripts.md"),
        README_END,
    ])


def update_readme(readme: Path, block: str) -> bool:
    text = readme.read_text()
    pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
    if not pattern.search(text):
        return False
    readme.write_text(pattern.sub(lambda _: block, text))
    return True


def write_outputs(run: dict, root: Path) -> list[Path]:
    written = []
    data = root / "docs" / "data" / "latest-run.json"
    data.parent.mkdir(parents=True, exist_ok=True)
    data.write_text(json.dumps(run, indent=1, ensure_ascii=False) + "\n")
    written.append(data)

    transcripts = root / "test_transcripts.md"
    transcripts.write_text(render_markdown(run) + "\n")
    written.append(transcripts)

    readme = root / "README.md"
    if readme.exists() and update_readme(readme, render_readme_block(run)):
        written.append(readme)
    return written
